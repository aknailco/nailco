-- 1. Products table
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  code        text unique not null,
  name        text not null,
  price       integer not null default 0 check (price >= 0),
  category    text not null default 'french',
  shape       text not null default 'Almond',
  description text not null default '',
  images      text[] not null default '{}',
  sort_order  integer not null default 0,
  visible     boolean not null default true,
  created_at  timestamptz not null default now()
);

-- 2. Admin list (only emails in this table can edit products)
create table if not exists public.admins (
  email text primary key
);

alter table public.products enable row level security;
alter table public.admins   enable row level security;

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- 3. Who can do what
drop policy if exists "Anyone can see visible products" on public.products;
drop policy if exists "Admins can add products"         on public.products;
drop policy if exists "Admins can edit products"        on public.products;
drop policy if exists "Admins can delete products"      on public.products;
drop policy if exists "Admins can see own admin row"    on public.admins;

create policy "Anyone can see visible products" on public.products
  for select using (visible or public.is_admin());
create policy "Admins can add products" on public.products
  for insert with check (public.is_admin());
create policy "Admins can edit products" on public.products
  for update using (public.is_admin()) with check (public.is_admin());
create policy "Admins can delete products" on public.products
  for delete using (public.is_admin());
create policy "Admins can see own admin row" on public.admins
  for select using (lower(email) = lower(coalesce(auth.jwt() ->> 'email', '')));

-- 4. Photo storage (public to view, admins only to upload/delete)
insert into storage.buckets (id, name, public)
values ('nail-images', 'nail-images', true)
on conflict (id) do update set public = true;

drop policy if exists "Anyone can view nail photos"   on storage.objects;
drop policy if exists "Admins can upload nail photos" on storage.objects;
drop policy if exists "Admins can change nail photos" on storage.objects;
drop policy if exists "Admins can delete nail photos" on storage.objects;

create policy "Anyone can view nail photos" on storage.objects
  for select using (bucket_id = 'nail-images');
create policy "Admins can upload nail photos" on storage.objects
  for insert with check (bucket_id = 'nail-images' and public.is_admin());
create policy "Admins can change nail photos" on storage.objects
  for update using (bucket_id = 'nail-images' and public.is_admin());
create policy "Admins can delete nail photos" on storage.objects
  for delete using (bucket_id = 'nail-images' and public.is_admin());

